#!/usr/bin/env python3
"""Generate per-pack catalog reference markdown from YAML (with --check drift gate)."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "catalog"
INDUSTRIES = CATALOG / "industries"
PACKS_FILE = CATALOG / "packs.yaml"
OUT_DIR = ROOT / "docs" / "catalog-packs"


def _load(path: Path) -> dict[str, Any]:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def _pack_ids() -> list[str]:
    data = _load(PACKS_FILE)
    return [row["pack"] for row in data.get("packs") or [] if row.get("pack")]


def render_pack_doc(pack_id: str) -> str:
    pack_dir = INDUSTRIES / pack_id
    pack_meta = _load(pack_dir / "pack.yaml")
    metrics_doc = _load(pack_dir / "metrics.yaml")
    options_doc = _load(pack_dir / "data_options.yaml")
    benchmarks_doc = _load(pack_dir / "benchmarks.yaml")

    industry = str(pack_meta.get("industry") or pack_id)
    metrics = metrics_doc.get("metrics") or {}
    options = options_doc.get("dataOptions") or {}
    benchmarks = benchmarks_doc.get("benchmarks") or {}

    lines = [
        f"# {industry} pack (`{pack_id}`)",
        "",
        "Auto-generated from `catalog/industries/` YAML. Do not edit by hand.",
        "",
        f"- Industry label: **{industry}**",
        f"- Metrics: **{len(metrics)}**",
        f"- Data options: **{len(options)}**",
        f"- Benchmark keys: **{len(benchmarks)}**",
        "",
        "## Data options",
        "",
    ]
    for key in sorted(options.keys()):
        opt = options[key] or {}
        name = str(opt.get("name") or key)
        field_count = len(opt.get("fields") or [])
        lines.append(f"- `{key}` — {name} ({field_count} fields)")
    lines.extend(["", "## Metrics (slug)", ""])
    for _mid, metric in sorted(metrics.items(), key=lambda item: str(item[1].get("slug") or "")):
        slug = str(metric.get("slug") or metric.get("name") or _mid)
        lines.append(f"- `{slug}` — {metric.get('name', '')}")
    lines.append("")
    return "\n".join(lines)


def write_all() -> list[Path]:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    index_lines = [
        "# Catalog pack reference",
        "",
        "Per-industry summaries generated by `scripts/generate_pack_reference_docs.py`.",
        "",
    ]
    for pack_id in _pack_ids():
        body = render_pack_doc(pack_id)
        path = OUT_DIR / f"{pack_id}.md"
        path.write_text(body, encoding="utf-8")
        written.append(path)
        index_lines.append(f"- [{pack_id}]({pack_id}.md)")
    index_lines.append("")
    index_path = OUT_DIR / "README.md"
    index_path.write_text("\n".join(index_lines), encoding="utf-8")
    written.append(index_path)
    return written


def check_drift() -> int:
    errors: list[str] = []
    for pack_id in _pack_ids():
        expected = render_pack_doc(pack_id)
        on_disk = OUT_DIR / f"{pack_id}.md"
        if not on_disk.is_file():
            errors.append(f"missing {on_disk.relative_to(ROOT)}")
            continue
        if on_disk.read_text(encoding="utf-8") != expected:
            errors.append(f"drift: {on_disk.relative_to(ROOT)}")
    index_expected = "\n".join(
        [
            "# Catalog pack reference",
            "",
            "Per-industry summaries generated by `scripts/generate_pack_reference_docs.py`.",
            "",
            *[f"- [{p}]({p}.md)" for p in _pack_ids()],
            "",
        ]
    )
    index_path = OUT_DIR / "README.md"
    if index_path.read_text(encoding="utf-8") != index_expected:
        errors.append("drift: docs/catalog-packs/README.md")
    if errors:
        for err in errors:
            print(f"ERROR: {err}", file=sys.stderr)
        return 1
    print(f"OK: {len(_pack_ids())} pack reference doc(s) match YAML")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when committed docs drift from YAML")
    args = parser.parse_args()
    if args.check:
        return check_drift()
    paths = write_all()
    print(f"Wrote {len(paths)} file(s) under {OUT_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
